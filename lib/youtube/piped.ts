const REQUEST_TIMEOUT_MS = 6_000;
const TOTAL_TIMEOUT_MS = 20_000;
const JSON_MAX_BYTES = 4 * 1024 * 1024;
const SUBTITLE_MAX_BYTES = 8 * 1024 * 1024;
const MAX_SEGMENTS = 30_000;
const MAX_TEXT_CHARACTERS = 2_000_000;

const object = (value: unknown): ObjectValue =>
  value !== null && typeof value === "object" && !Array.isArray(value) ? value as ObjectValue : {};
const array = (value: unknown): unknown[] => Array.isArray(value) ? value : [];
const string = (value: unknown): string => typeof value === "string" ? value : "";

function safePublicHttps(raw: string): string | null {
  let url: URL;
  try { url = new URL(raw); } catch { return null; }
  if (url.protocol !== "https:" || url.username || url.password || (url.port && url.port !== "443")) return null;
  const host = url.hostname.toLowerCase();
  if (!host || host === "localhost" || host.endsWith(".local") || /^\d+(?:\.\d+){3}$/.test(host) || host.includes(":")) return null;
  return url.toString();
}

async function readBody(response: Response, maxBytes: number): Promise<string> {
  if (!response.ok || !response.body) throw new Error(`HTTP ${response.status}`);
  const declared = Number(response.headers.get("content-length"));
  if (Number.isFinite(declared) && declared > maxBytes) throw new Error("Response too large");
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let size = 0;
  let body = "";
  try {
    for (;;) {
      const part = await reader.read();
      if (part.done) break;
      size += part.value.byteLength;
      if (size > maxBytes) throw new Error("Response too large");
      body += decoder.decode(part.value, { stream: true });
    }
    body += decoder.decode();
    return body;
  } finally {
    await reader.cancel().catch(() => undefined);
  }
}

async function fetchText(url: string, maxBytes: number, deadline: number, accept: string): Promise<string> {
  const remaining = deadline - Date.now();
  if (remaining <= 0) throw new CaptionError("YOUTUBE_TIMEOUT");
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), Math.min(REQUEST_TIMEOUT_MS, remaining));
  try {
    const response = await fetch(url, {
      headers: { "Accept": accept, "User-Agent": "TranscriptGenerator/1.0" },
      cache: "no-store",
      redirect: "error",
      signal: controller.signal,
    });
    return await readBody(response, maxBytes);
  } catch (error) {
    if (controller.signal.aborted) throw new CaptionError("YOUTUBE_TIMEOUT");
    if (error instanceof CaptionError) throw error;
    throw new CaptionError("YOUTUBE_FAILURE");
  } finally {
    clearTimeout(timer);
    controller.abort();
  }
}

async function fetchJson(url: string, deadline: number): Promise<unknown> {
  const text = await fetchText(url, JSON_MAX_BYTES, deadline, "application/json");
  try { return JSON.parse(text) as unknown; } catch { throw new CaptionError("YOUTUBE_FAILURE"); }
}

function decodeEntities(value: string): string {
  return value
    .replace(/&#(\d+);/g, (_, raw: string) => String.fromCodePoint(Math.min(Number(raw), 0x10ffff)))
    .replace(/&#x([0-9a-f]+);/gi, (_, raw: string) => String.fromCodePoint(Math.min(parseInt(raw, 16), 0x10ffff)))
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&quot;/gi, "\"")
    .replace(/&#39;|&apos;/gi, "'");
}

function parseTime(raw: string): number | null {
  const value = raw.trim().replace(",", ".");
  if (/^\d+(?:\.\d+)?s$/i.test(value)) return Number(value.slice(0, -1));
  const parts = value.split(":");
  if (parts.length < 2 || parts.length > 3) return null;
  const seconds = Number(parts.pop());
  const minutes = Number(parts.pop());
  const hours = parts.length ? Number(parts.pop()) : 0;
  if (![seconds, minutes, hours].every(Number.isFinite) || seconds < 0 || minutes < 0 || hours < 0) return null;
  return hours * 3600 + minutes * 60 + seconds;
}

function addSegment(segments: TranscriptSegment[], text: string, start: number, duration: number, state: { characters: number }) {
  const clean = decodeEntities(text)
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]*>/g, "")
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!clean) return;
  const previous = segments[segments.length - 1];
  if (previous?.text === clean && Math.abs(previous.start - start) < 0.001) return;
  state.characters += clean.length;
  if (state.characters > MAX_TEXT_CHARACTERS || segments.length >= MAX_SEGMENTS) throw new CaptionError("YOUTUBE_FAILURE");
  segments.push({ text: clean, start, duration: Math.max(0, duration) });
}

function parseVtt(input: string): TranscriptSegment[] {
  const normalized = input.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
  if (!/^WEBVTT(?:\s|$)/.test(normalized)) throw new CaptionError("YOUTUBE_FAILURE");
  const segments: TranscriptSegment[] = [];
  const state = { characters: 0 };
  for (const block of normalized.split(/\n{2,}/)) {
    const lines = block.split("\n").map((line) => line.trimEnd());
    const timingIndex = lines.findIndex((line) => line.includes("-->"));
    if (timingIndex < 0) continue;
    const [startRaw, endAndSettings] = lines[timingIndex].split("-->", 2);
    const endRaw = endAndSettings?.trim().split(/\s+/, 1)[0];
    const start = parseTime(startRaw);
    const end = endRaw ? parseTime(endRaw) : null;
    if (start === null || end === null || end < start) continue;
    addSegment(segments, lines.slice(timingIndex + 1).join(" "), start, end - start, state);
  }
  if (!segments.length) throw new CaptionError("NO_CAPTIONS");
  return segments;
}

function parseTtml(input: string): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  const state = { characters: 0 };
  const pPattern = /<p\b([^>]*)>([\s\S]*?)<\/p>/gi;
  let match: RegExpExecArray | null;
  while ((match = pPattern.exec(input))) {
    const attrs = match[1];
    const body = match[2];
    const beginMatch = /\bbegin=["']([^"']+)["']/i.exec(attrs);
    const endMatch = /\bend=["']([^"']+)["']/i.exec(attrs);
    const durMatch = /\bdur=["']([^"']+)["']/i.exec(attrs);
    const start = beginMatch ? parseTime(beginMatch[1]) : null;
    if (start === null) continue;
    const end = endMatch ? parseTime(endMatch[1]) : null;
    const dur = durMatch ? parseTime(durMatch[1]) : null;
    const duration = end !== null ? end - start : dur;
    if (duration === null || duration < 0) continue;
    addSegment(segments, body, start, duration, state);
  }
  if (!segments.length) throw new CaptionError("NO_CAPTIONS");
  return segments;
}

function parseSubtitle(input: string): TranscriptSegment[] {
  const trimmed = input.trimStart();
  if (trimmed.startsWith("WEBVTT")) return parseVtt(input);
  if (/<(?:tt|transcript)\b/i.test(trimmed) || /<p\b[^>]*\bbegin=/i.test(trimmed)) return parseTtml(input);
  throw new CaptionError("YOUTUBE_FAILURE");
}

function normalizeTracks(value: unknown): PipedTrack[] {
  const tracks: PipedTrack[] = [];
  for (const raw of array(value).slice(0, 200)) {
    const item = object(raw);
    const code = string(item.code).trim();
    const name = (string(item.name) || code).trim();
    const url = safePublicHttps(string(item.url));
    if (!/^[a-zA-Z]{2,3}(?:-[a-zA-Z0-9]{2,8})*$/.test(code) || !name || !url) continue;
    tracks.push({ name: name.slice(0, 200), code, autoGenerated: item.autoGenerated === true, url, index: tracks.length });
  }
  return tracks;
}

function selectedTrack(tracks: PipedTrack[], language?: string): PipedTrack | undefined {
  if (language?.startsWith("piped:")) {
    const index = Number(language.slice(6));
    if (Number.isInteger(index) && index >= 0) return tracks[index];
  }
  if (language) return tracks.find((track) => track.code === language && !track.autoGenerated) ?? tracks.find((track) => track.code === language);
  return tracks.find((track) => track.code.startsWith("en") && !track.autoGenerated)
    ?? tracks.find((track) => track.code.startsWith("en"))
    ?? tracks[0];
}

function languages(tracks: PipedTrack[]): CaptionLanguage[] {
  return tracks.map((track) => ({
    id: `piped:${track.index}`,
    label: track.autoGenerated && !/auto|generated/i.test(track.name) ? `${track.name} (auto-generated)` : track.name,
    code: track.code,
  }));
}

async function retrieveFromInstance(base: string, videoId: string, language: string | undefined, deadline: number): Promise<TranscriptResult> {
  const info = object(await fetchJson(`${base}/streams/${encodeURIComponent(videoId)}`, deadline));
  const title = string(info.title).trim();
  const channel = (string(info.uploader) || string(info.uploaderName)).trim();
  if (!title) throw new CaptionError("YOUTUBE_FAILURE");

  const tracks = normalizeTracks(info.subtitles);
  if (!tracks.length) throw new CaptionError("NO_CAPTIONS");
  const selected = selectedTrack(tracks, language);
  if (!selected) throw new CaptionError("LANGUAGE_UNAVAILABLE");

  const subtitle = await fetchText(selected.url, SUBTITLE_MAX_BYTES, deadline, "text/vtt,application/ttml+xml,text/xml,text/plain;q=0.9,*/*;q=0.1");
  const segments = parseSubtitle(subtitle);
  const durationRaw = Number(info.duration ?? info.lengthSeconds);

  return {
    videoId,
    title: title.slice(0, 1000),
    channel: channel.slice(0, 300),
    thumbnail: string(info.thumbnailUrl) || `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
    duration: Number.isFinite(durationRaw) && durationRaw > 0 ? durationRaw : null,
    languages: languages(tracks),
    language: `piped:${selected.index}`,
    segments,
  };
}

export async function retrieveTranscriptViaPiped(input: string, language?: string): Promise<TranscriptResult> {
  const { videoId } = parseYouTubeUrl(input);
  const deadline = Date.now() + TOTAL_TIMEOUT_MS;
  let sawNoCaptions = false;
  let sawLanguageUnavailable = false;

  for (const base of INSTANCES) {
    if (Date.now() >= deadline) break;
    try {
      const result = await retrieveFromInstance(base, videoId, language, deadline);
      console.info("Caption fallback succeeded", { provider: "piped", host: new URL(base).hostname });
      return result;
    } catch (error) {
      if (error instanceof CaptionError && error.code === "NO_CAPTIONS") sawNoCaptions = true;
      else if (error instanceof CaptionError && error.code === "LANGUAGE_UNAVAILABLE") sawLanguageUnavailable = true;
      console.warn("Caption fallback instance failed", { provider: "piped", host: new URL(base).hostname });
    }
  }

  if (sawLanguageUnavailable) throw new CaptionError("LANGUAGE_UNAVAILABLE");
  if (sawNoCaptions) throw new CaptionError("NO_CAPTIONS");
  if (Date.now() >= deadline) throw new CaptionError("YOUTUBE_TIMEOUT");
  throw new CaptionError("YOUTUBE_FAILURE");
}
